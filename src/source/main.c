#define DEFAULT_PORT 8888
#define DEFAULT_SERVER_IP "192.168.1.1"
#define CONFIG_FILE "config.ini"
#define MAX_LINE 256
#define LCD_TOGGLE_KEY KEY_L
#define CONNECTION_TIMEOUT_MS 5000

/* The 3DS has no clickable sticks. BIT(12) and BIT(13) are unused by libctru
   (BIT14/15 are KEY_ZL/KEY_ZR), so they carry virtual L3/R3 generated by the
   touch screen: left half = L3, right half = R3. */
#define VIRTUAL_L3 0x1000
#define VIRTUAL_R3 0x2000
#define TOUCH_SPLIT_X 160

typedef struct {
    u32 buttons;            // 4 bytes
    circlePosition circlepad; // 4 bytes (x, y as s16)
    circlePosition cstick;  // 4 bytes (x, y as s16)
} controllerstate;

typedef struct {
    char serverip[64];
    int port;
    u32 lcdtogglekey;
} config;

void readconfigfile(config *cfg) {
    strcpy(cfg->serverip, DEFAULT_SERVER_IP);
    cfg->port = DEFAULT_PORT;
    cfg->lcdtogglekey = LCD_TOGGLE_KEY;
    
    FILE *file = fopen(CONFIG_FILE, "r");
    if (!file) {
        printf("config.ini not found at %s, using defaults\n", CONFIG_FILE);
        printf("creating default config file...\n");
        
        file = fopen(CONFIG_FILE, "w");
        if (file) {
            fprintf(file, "serverip=%s\n", DEFAULT_SERVER_IP);
            fprintf(file, "port=%d\n", DEFAULT_PORT);
            fprintf(file, "lcdtogglekey=KEY_L\n");
            fclose(file);
            printf("default config file created at %s\n", CONFIG_FILE);
        } else {
            printf("failed to create default config file\n");
        }
        return;
    }
    
    char line[MAX_LINE];
    while (fgets(line, MAX_LINE, file)) {
        size_t len = strlen(line);
        if (len > 0 && line[len-1] == '\n') {
            line[len-1] = '\0';
        }
        
        char *key = strtok(line, "=");
        char *value = strtok(NULL, "=");
        
        if (key && value) {
            while (*key && (*key == ' ' || *key == '\t')) key++;
            while (*value && (*value == ' ' || *value == '\t')) value++;
            
            if (strcmp(key, "serverip") == 0) {
                strcpy(cfg->serverip, value);
            } else if (strcmp(key, "port") == 0) {
                cfg->port = atoi(value);
            } else if (strcmp(key, "lcdtogglekey") == 0) {
                if (strcmp(value, "KEY_L") == 0) cfg->lcdtogglekey = KEY_L;
                else if (strcmp(value, "KEY_R") == 0) cfg->lcdtogglekey = KEY_R;
                else if (strcmp(value, "KEY_ZL") == 0) cfg->lcdtogglekey = KEY_ZL;
                else if (strcmp(value, "KEY_ZR") == 0) cfg->lcdtogglekey = KEY_ZR;
                else if (strcmp(value, "KEY_SELECT") == 0) cfg->lcdtogglekey = KEY_SELECT;
            }
        }
    }
    
    fclose(file);
    printf("config loaded from %s\n", CONFIG_FILE);
}

int initsocket(const config *cfg) {
    int sockfd;
    struct sockaddr_in serveraddr;

    if ((sockfd = socket(AF_INET, SOCK_DGRAM, 0)) < 0) {
        printf("socket creation failed\n");
        return -1;
    }

    memset(&serveraddr, 0, sizeof(serveraddr));
    
    serveraddr.sin_family = AF_INET;
    serveraddr.sin_port = htons(cfg->port);
    
    if (inet_pton(AF_INET, cfg->serverip, &serveraddr.sin_addr) <= 0) {
        printf("invalid address\n");
        close(sockfd);
        return -1;
    }
    
    if (connect(sockfd, (struct sockaddr*)&serveraddr, sizeof(serveraddr)) < 0) {
        printf("connection failed\n");
        close(sockfd);
        return -1;
    }
    
    int flags = fcntl(sockfd, F_GETFL, 0);
    fcntl(sockfd, F_SETFL, flags | O_NONBLOCK);
    
    return sockfd;
}

/* Non-blocking heartbeat. The old version sat in select() for up to 2 seconds
   waiting for a pong, which froze the whole send loop: the stick/button state
   kept repeating the last value and the game felt unresponsive. */
static u32 g_ping_at = 0;
static u32 g_pong_at = 0;

int checkconnection(int sockfd) {
    if (sockfd < 0) return 0;

    u32 now = osGetTime();

    if (now - g_ping_at > 1000) {
        send(sockfd, "ping", 5, 0);
        g_ping_at = now;
    }

    char buf[8];
    int n = recv(sockfd, buf, sizeof(buf), MSG_DONTWAIT);
    if (n > 0) {
        g_pong_at = now;
    }

    if (g_pong_at == 0) {
        g_pong_at = now;
    }

    return (now - g_pong_at) < 3000;
}

int sendcontrollerstate(int sockfd, controllerstate *state) {
    return send(sockfd, state, sizeof(controllerstate), 0);
}

void saveconfigfile(const config *cfg) {
    FILE *file = fopen(CONFIG_FILE, "w");
    if (!file) return;
    fprintf(file, "serverip=%s\n", cfg->serverip);
    fprintf(file, "port=%d\n", cfg->port);
    fprintf(file, "lcdtogglekey=KEY_L\n");
    fclose(file);
}

void getbatterystatus(char *buffer, size_t size) {
    u8 percentage;
    PTMU_GetBatteryLevel(&percentage);
    
    u8 charging;
    PTMU_GetBatteryChargeState(&charging);
    
    char icon[6];
    int level = percentage;
    
    if (level < 0) level = 0;
    if (level > 4) level = 4;
    
    for (int i = 0; i < 5; i++) {
        icon[i] = (i <= level) ? '|' : ' ';
    }
    icon[5] = '\0';
    
    if (charging) {
        snprintf(buffer, size, "[%s] +", icon);
    } else {
        snprintf(buffer, size, "[%s] %d%%", icon, (level + 1) * 20);
    }
}

static PrintConsole *g_top_con = NULL;
static PrintConsole *g_bottom_con = NULL;

void printstatusmessage(int sockfd, const config *cfg, int isconnected, int lcdstate) {
    if (!g_bottom_con) return;
    char batterystatus[32];
    getbatterystatus(batterystatus, sizeof(batterystatus));

    consoleSelect(g_bottom_con);
    printf("\x1b[3;11H%-24s", cfg->serverip);
    printf("\x1b[4;11H%-6d", cfg->port);
    if (isconnected)
        printf("\x1b[5;11H\x1b[32mCONNECTED\x1b[0m     ");
    else
        printf("\x1b[5;11H\x1b[31mOFFLINE\x1b[0m       ");
    printf("\x1b[6;11H%-12s", batterystatus);
    consoleSelect(g_top_con);
}

static void bottom_ui_init(void) {
    if (!g_bottom_con) return;
    consoleSelect(g_bottom_con);
    consoleClear();
    const char *sep = "+--------------------------------------+";
    printf("\x1b[1;1H%s", sep);
    printf("\x1b[2;1H|         3DS CONTROLLER               |");
    printf("\x1b[3;1H| IP      ------------------------     |");
    printf("\x1b[4;1H| Port    ----                         |");
    printf("\x1b[5;1H| Status  OFFLINE                      |");
    printf("\x1b[6;1H| Battery --                           |");
    printf("\x1b[7;1H%s", sep);
    printf("\x1b[8;1H| L3 [    ]     R3 [    ]              |");
    printf("\x1b[9;1H%s", sep);
    printf("\x1b[10;1H| L+START      : change IP             |");
    printf("\x1b[11;1H| L+START+SEL  : exit                  |");
    printf("\x1b[12;1H%s", sep);
    consoleSelect(g_top_con);
}

static void bottom_ui_l3r3(bool l3, bool r3) {
    if (!g_bottom_con) return;
    consoleSelect(g_bottom_con);
    printf("\x1b[8;6H%s", l3 ? "[ ON ]" : "[    ]");
    printf("\x1b[8;20H%s", r3 ? "[ ON ]" : "[    ]");
    consoleSelect(g_top_con);
}

int main(int argc, char **argv) {
    gfxInitDefault();
    g_top_con = consoleInit(GFX_TOP, NULL);
    g_bottom_con = consoleInit(GFX_BOTTOM, NULL);
    consoleSelect(g_top_con);
    
    socInit((u32*)memalign(0x1000, 0x100000), 0x100000);
    ptmuInit();
    
    config cfg;
    readconfigfile(&cfg);
    
    bottom_ui_init();

    /* Top screen is not used anymore: keep its backlight off to save battery */
    gspLcdInit();
    GSPLCD_PowerOffBacklight(GSPLCD_SCREEN_TOP);

    printf("3ds controller\n");
    printf("connecting to pc at %s:%d...\n", cfg.serverip, cfg.port);
    
    int sockfd = initsocket(&cfg);
    int isconnected = 0;
    u32 combo_hold = 0;
    bool last_l3 = false, last_r3 = false;
    int lcdstate = 1;
    u32 lcdtoggleheldtime = 0;
    
    printf("\ncalibrating circle pad...\n");
    printf("leave circle pad untouched\n");
    
    for (int i = 0; i < 60; i++) {
        gfxFlushBuffers();
        gfxSwapBuffers();
        gspWaitForVBlank();
    }
    
    printf("\ncalibration complete!\n");
    
    u32 laststatusupdate = 0;
    
    while (aptMainLoop()) {
        hidScanInput();
        u32 keysdown = hidKeysHeld();
        
        if ((keysdown & (KEY_L | KEY_START | KEY_SELECT)) == (KEY_L | KEY_START | KEY_SELECT)) {
            break;
        }

        /* L + START held for ~600ms: edit the PC IP address.
           The hold requirement keeps it from clashing with the 3-key exit combo. */
        if ((keysdown & (KEY_L | KEY_START)) == (KEY_L | KEY_START) && !(keysdown & KEY_SELECT)) {
            u32 now = osGetTime();
            if (combo_hold == 0) {
                combo_hold = now ? now : 1;
            } else if (now - combo_hold > 600) {
                combo_hold = 0;
                SwkbdState swkbd;
                char ipbuf[64];
                memset(ipbuf, 0, sizeof(ipbuf));
                snprintf(ipbuf, sizeof(ipbuf), "%s", cfg.serverip);
                swkbdInit(&swkbd, SWKBD_TYPE_NORMAL, 2, 15);
                swkbdSetHintText(&swkbd, "PC IP address");
                swkbdSetInitialText(&swkbd, cfg.serverip);
                swkbdSetValidation(&swkbd, SWKBD_NOTEMPTY_NOTBLANK, 0, 0);
                if (swkbdInputText(&swkbd, ipbuf, sizeof(ipbuf)) == 0 && ipbuf[0] != '\0') {
                    snprintf(cfg.serverip, sizeof(cfg.serverip), "%s", ipbuf);
                    saveconfigfile(&cfg);
                    if (sockfd >= 0) {
                        close(sockfd);
                        sockfd = -1;
                    }
                    isconnected = 0;
                    bottom_ui_init();
                }
            }
        } else {
            combo_hold = 0;
        }
        
        u32 currenttime = osGetTime();

        /* Non-blocking: safe to call every frame */
        isconnected = checkconnection(sockfd);
        if (!isconnected && sockfd >= 0) {
            close(sockfd);
            sockfd = -1;
            g_ping_at = 0;
            g_pong_at = 0;
        }
        if (!isconnected && sockfd < 0) {
            sockfd = initsocket(&cfg);
            g_ping_at = 0;
            g_pong_at = 0;
        }
        
        /* L alone toggles the backlight, but L is also the IP-edit modifier now,
           so skip the toggle while START is held (otherwise the combo would
           black out the screens right after the keyboard closes). */
        if ((keysdown & cfg.lcdtogglekey) && !(keysdown & KEY_START)) {
            if (lcdtoggleheldtime == 0) {
                lcdtoggleheldtime = currenttime;
            } else if (currenttime - lcdtoggleheldtime > 1000) {
                lcdstate = !lcdstate;
                if (lcdstate) {
                    gspLcdInit();
                    GSPLCD_PowerOnBacklight(GSPLCD_SCREEN_BOTH);
                } else {
                    GSPLCD_PowerOffBacklight(GSPLCD_SCREEN_BOTH);
                }
                lcdtoggleheldtime = currenttime;
            }
        } else {
            lcdtoggleheldtime = 0;
        }
        
        controllerstate state;
        memset(&state, 0, sizeof(controllerstate));
        /* Keep only the real buttons (bit 0-15); drop KEY_TOUCH / CPAD / CSTICK bits */
        state.buttons = keysdown & 0xFFFF;

        /* Virtual L3/R3: left half of the touch screen = L3, right half = R3 */
        touchPosition touch;
        hidTouchRead(&touch);
        if (touch.px != 0 || touch.py != 0) {
            if (touch.px < TOUCH_SPLIT_X)
                state.buttons |= VIRTUAL_L3;
            else
                state.buttons |= VIRTUAL_R3;
        }

        hidCircleRead(&state.circlepad);
        hidCstickRead(&state.cstick);
        
        if (isconnected) {
            sendcontrollerstate(sockfd, &state);
        }

        {
            bool l3 = (state.buttons & VIRTUAL_L3) != 0;
            bool r3 = (state.buttons & VIRTUAL_R3) != 0;
            if (l3 != last_l3 || r3 != last_r3) {
                bottom_ui_l3r3(l3, r3);
                last_l3 = l3;
                last_r3 = r3;
            }
        }
        
        if (currenttime - laststatusupdate > 3000) {
            printstatusmessage(sockfd, &cfg, isconnected, lcdstate);
            laststatusupdate = currenttime;
        }
        
        gfxFlushBuffers();
        gfxSwapBuffers();
        
        gspWaitForVBlank();

        // i accidently flooded my network so this was added lol
        /* ~30 Hz total: VBlank (16.6ms) + 16.6ms sleep */
        svcSleepThread(16667000);
    }
    
    if (sockfd >= 0) {
        close(sockfd);
    }
    
    ptmuExit();
    socExit();
    gfxExit();
    return 0;
}